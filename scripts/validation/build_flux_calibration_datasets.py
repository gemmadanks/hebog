"""Build the M1 flux and uncertainty calibration population.

Writes ``config/datasets/m1-flux-calibration.json``, a development-role
dataset manifest of ten 1,024-pixel realizations: five with
pixel-independent noise and five with beam-correlated noise. Each holds 64
isolated sources on an 8-by-8 grid, cycling through peak signal-to-noise 10,
20 and 50 and sizes of 1 to 1.5 times the beam, with a sub-pixel jitter drawn
from the realization's seed.

Every realization uses generator version 4, whose seeds give independent
noise fields. The 23 September population used versions 2 and 3 with seeds
2026091700 to 2026091709, and its white-noise images were one field
rearranged (plan task 48); these seeds are disjoint from those and from
every checked-in manifest.

Run ``uv run python scripts/validation/build_flux_calibration_datasets.py``
and commit the manifest. ``--realizations N --output PATH`` writes the first
N realizations of each class elsewhere, for a larger diagnostic; the first
five are the committed ones.
``scripts/validation/measure_component_uncertainty_calibration.py`` reads
only the manifest.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

import numpy as np

from hebog.validation.datasets import (
    DatasetManifest,
    SyntheticRecipe,
    recipe_sha256,
)

_ROOT = Path(__file__).resolve().parents[2]
_OUTPUT = _ROOT / "config/datasets/m1-flux-calibration.json"
_SEED_BASE = 2026100510
_REALIZATIONS = 5
_NOISE_RMS = 1e-4
_BEAM_MAJOR_FWHM_PIXELS = 5.0
_BEAM_MINOR_FWHM_PIXELS = 4.0
_FWHM_PER_SIGMA = 2.0 * math.sqrt(2.0 * math.log(2.0))
_PIXEL_SCALE_DEGREES = 1.5 / 3600.0
_GRID = 8
_SIZE = 1024
_SNRS = (10.0, 20.0, 50.0)
# Beam-sized sources cannot distinguish a correct shape from one always
# constrained to the beam, because their truth is the beam. The two factors
# between them are the ones where publishing the beam would bias sizes and
# fluxes low, and a free fit would bias them high.
_SIZE_FACTORS = (1.0, 1.15, 1.3, 1.5)


def _sources(seed: int) -> list[dict[str, float]]:
    """Isolated sources cycling through SNR and size, with sub-pixel jitter."""
    generator = np.random.default_rng(seed)
    spacing = _SIZE / _GRID
    sources: list[dict[str, float]] = []
    for index in range(_GRID * _GRID):
        row, column = divmod(index, _GRID)
        factor = _SIZE_FACTORS[index % len(_SIZE_FACTORS)]
        snr = _SNRS[(index // len(_SIZE_FACTORS)) % len(_SNRS)]
        sources.append(
            {
                "x_pixel": round(
                    spacing * (column + 0.5) + generator.uniform(-0.5, 0.5), 4
                ),
                "y_pixel": round(
                    spacing * (row + 0.5) + generator.uniform(-0.5, 0.5), 4
                ),
                "peak_flux_jy_per_beam": snr * _NOISE_RMS,
                "major_sigma_pixels": factor
                * _BEAM_MAJOR_FWHM_PIXELS
                / _FWHM_PER_SIGMA,
                "minor_sigma_pixels": factor
                * _BEAM_MINOR_FWHM_PIXELS
                / _FWHM_PER_SIGMA,
                "rotation_degrees_counterclockwise_from_x": 0.0,
            }
        )
    return sources


def _recipe(seed: int, *, correlated: bool) -> SyntheticRecipe:
    """Return one realization's recipe."""
    document: dict[str, Any] = {
        "generator": "hebog.synthetic.gaussian-noise",
        "generator_version": 4,
        "seed": seed,
        "shape_yx": [_SIZE, _SIZE],
        "background": 0.0,
        "noise_rms": _NOISE_RMS,
        "sources": _sources(seed),
    }
    if correlated:
        document["noise_correlation"] = {
            "major_fwhm_pixels": _BEAM_MAJOR_FWHM_PIXELS,
            "minor_fwhm_pixels": _BEAM_MINOR_FWHM_PIXELS,
            "position_angle_degrees": 0.0,
            "truncation_sigma": 4.0,
        }
    return SyntheticRecipe.model_validate(document)


def _dataset(realization: int, *, correlated: bool) -> dict[str, Any]:
    """Return one realization's dataset record."""
    noise = "correlated" if correlated else "white"
    recipe = _recipe(
        _SEED_BASE + 2 * realization + int(correlated),
        correlated=correlated,
    )
    return {
        "identifier": f"calibration-{noise}-{realization}",
        "role": "development",
        "purpose": (
            f"Realization {realization} of the M1 flux and uncertainty "
            f"calibration population in {noise} noise: 64 isolated sources "
            "at SNR 10, 20 and 50, one to 1.5 beams wide."
        ),
        "provenance": (
            "Generated by scripts/validation/build_flux_calibration_"
            "datasets.py for plan task 48; generator version 4, "
            "seed-disjoint from earlier manifests and from the 23 September "
            "population."
        ),
        "redistribution": "generated-locally",
        "beam": {
            "major_fwhm_pixels": _BEAM_MAJOR_FWHM_PIXELS,
            "minor_fwhm_pixels": _BEAM_MINOR_FWHM_PIXELS,
            "position_angle_degrees": 0.0,
        },
        "wcs": {
            "frame": "icrs",
            "reference_pixel_xy": [(_SIZE - 1) / 2.0, (_SIZE - 1) / 2.0],
            "reference_sky_degrees": [180.0, 45.0],
            "pixel_scale_degrees_xy": [
                -_PIXEL_SCALE_DEGREES,
                _PIXEL_SCALE_DEGREES,
            ],
            "rotation_degrees_counterclockwise": 0.0,
        },
        "expected_statistics": {
            "background_jy_per_beam": 0.0,
            "noise_rms_jy_per_beam": _NOISE_RMS,
            "finite_fraction": 1.0,
        },
        "recipe": recipe.model_dump(mode="json"),
        "recipe_sha256": recipe_sha256(recipe),
    }


def build_manifest(realizations: int = _REALIZATIONS) -> dict[str, Any]:
    """Return the validated manifest of the first realizations a class."""
    document: dict[str, Any] = {
        "schema_version": 1,
        "manifest_id": "m1-flux-calibration",
        "datasets": [
            _dataset(realization, correlated=correlated)
            for correlated in (False, True)
            for realization in range(realizations)
        ],
    }
    DatasetManifest.model_validate(document)
    return document


def main() -> None:
    """Write the manifest, or with ``--check`` fail if it is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if stale")
    parser.add_argument(
        "--realizations",
        type=int,
        default=_REALIZATIONS,
        help="realizations of each noise class (default: the committed five)",
    )
    parser.add_argument("--output", type=Path, default=_OUTPUT)
    args = parser.parse_args()
    if args.realizations < 1:
        raise SystemExit("--realizations must be at least 1")
    document = build_manifest(args.realizations)
    text = json.dumps(document, indent=2, sort_keys=True) + "\n"
    if args.check:
        if args.output.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{args.output} is stale; rerun without --check")
        return
    args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
