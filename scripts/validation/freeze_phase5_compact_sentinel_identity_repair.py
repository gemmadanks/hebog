def _json_bytes(value: object) -> bytes:
    """Return exact canonical checked-in JSON bytes."""
    return (
        json.dumps(value, allow_nan=False, indent=2, sort_keys=True) + "\n"
    ).encode()


def _bytes_sha256(value: bytes) -> str:
    """Hash generated bytes before opening a target."""
    return hashlib.sha256(value).hexdigest()


def _json_object(path: Path) -> dict[str, Any]:
    """Load one required JSON object."""
    value: object = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"repair input must be a JSON object: {path}")
    return cast(dict[str, Any], value)


def _bindings(root: Path, paths: dict[str, str]) -> dict[str, object]:
    """Bind every exact repair program or fixture."""
    return {
        name: {"path": path, "sha256": file_sha256(root / path)}
        for name, path in sorted(paths.items())
    }


def _require_lineage(root: Path) -> dict[str, Any]:
    """Verify the approved review and complete failed-attempt lineage."""
    expected = (
        (_PRE_REVIEW, _PRE_REVIEW_SHA256),
        (_PARENT_IDENTITY, _PARENT_IDENTITY_SHA256),
        (_FAILED_DECISION, _FAILED_DECISION_SHA256),
        (_FAILED_OUTPUT, _FAILED_OUTPUT_SHA256),
        (_MANIFEST, _MANIFEST_SHA256),
    )
    for relative, digest in expected:
        path = root / relative
        if not path.is_file() or file_sha256(path) != digest:
            raise ValueError(
                f"compact sentinel repair input changed: {relative}"
            )
    return _json_object(root / _PARENT_IDENTITY)


