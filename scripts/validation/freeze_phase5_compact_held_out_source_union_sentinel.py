def _json_bytes(value: object) -> bytes:
    """Return exact checked-in JSON presentation bytes."""
    return (
        json.dumps(value, allow_nan=False, indent=2, sort_keys=True) + "\n"
    ).encode()


def _bytes_sha256(value: bytes) -> str:
    """Hash generated bytes before any output is opened."""
    return hashlib.sha256(value).hexdigest()


def _bindings(root: Path, paths: dict[str, str]) -> dict[str, object]:
    """Bind each exact program or fixture file by content."""
    return {
        name: {"path": path, "sha256": file_sha256(root / path)}
        for name, path in sorted(paths.items())
    }


def _population_program(root: Path) -> dict[str, Any]:
    """Load the metadata-only population without invoking its CLI."""
    return runpy.run_path(str(root / _PROGRAM_PATHS["population"]))


def _verified_reviews(root: Path) -> dict[str, object]:
    """Require both approved prospective reviews byte for byte."""
    reviews = {
        "root_cause": (_ROOT_CAUSE_REVIEW, _ROOT_CAUSE_REVIEW_SHA256),
        "source_union_adapters": (_ADAPTER_REVIEW, _ADAPTER_REVIEW_SHA256),
    }
    for path, digest in reviews.values():
        if file_sha256(root / path) != digest:
            raise ValueError("compact sentinel approved review changed")
    return {
        name: {"path": path.as_posix(), "sha256": digest}
        for name, (path, digest) in reviews.items()
    }


