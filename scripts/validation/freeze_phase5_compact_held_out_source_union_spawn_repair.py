def _write(path: Path, value: object) -> None:
    """Write one new immutable record without overwrite."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as stream:
        stream.write(_json_bytes(value))


def freeze_records(arguments: argparse.Namespace) -> None:
    """Validate all targets before publishing replacement records."""
    root = arguments.repository_root.resolve()
    output_root = arguments.output_root.resolve()
    implementation, identity = build_records(root)
    records = ((_IMPLEMENTATION, implementation), (_IDENTITY, identity))
    for relative, _value in records:
        target = output_root / relative
        if target.exists():
            raise FileExistsError(f"refusing to overwrite {target}")
    for relative, value in records:
        _write(output_root / relative, value)


def _parse_args() -> argparse.Namespace:
    """Parse source and output repository roots."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository-root", type=Path, default=_ROOT)
    parser.add_argument("--output-root", type=Path, default=_ROOT)
    return parser.parse_args()


def main() -> None:
    """Freeze the exact non-executable process repair record set."""
    freeze_records(_parse_args())


if __name__ == "__main__":
    main()
