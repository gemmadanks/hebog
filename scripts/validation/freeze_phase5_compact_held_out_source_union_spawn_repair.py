def _json_object(path: Path) -> dict[str, Any]:
    """Load one required JSON object."""
    value: object = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"JSON document must be an object: {path}")
    return cast(dict[str, Any], value)


def _json_bytes(value: object) -> bytes:
    """Return the canonical checked-in JSON presentation."""
    return (
        json.dumps(value, allow_nan=False, indent=2, sort_keys=True) + "\n"
    ).encode()


def _bytes_sha256(value: bytes) -> str:
    """Hash generated bytes before opening any output."""
    return hashlib.sha256(value).hexdigest()


def _require(path: Path, expected_sha256: str, name: str) -> None:
    """Require one immutable predecessor by exact bytes."""
    if not path.is_file() or file_sha256(path) != expected_sha256:
        raise ValueError(f"source-union spawn-repair {name} changed")


def _repair_bindings(root: Path) -> dict[str, object]:
    """Bind each isolated process repair program by content."""
    return {
        name: {"path": path, "sha256": file_sha256(root / path)}
        for name, path in sorted(_REPAIR_PROGRAM_PATHS.items())
    }


