"""Build the generated size and density ladder of the execution profile.

Writes ``config/datasets/complete-execution-profile.json``, a
development-role manifest of eight images: 512, 1,024, 2,048 and 4,096
pixels per side, each as noise only and as a dense field of 256 sources per
1,024²
(about twice the densest LoTSS-DR3 quick-check cut-out). Source density per
pixel is the same at every size, so ``profile_complete_execution.py`` can
separate the cost of image size from the cost of sources. The 4,096-pixel
pair is the smallest that holds more than one admitted tile core, so it is
also the smallest that can separate state scaling with the tile from state
scaling with the image. Sources are
isolated beam-shaped Gaussians with SNR 5 to 50 on a jittered grid, and noise
is beam-correlated, as in restored radio images. The images carry no
scientific authority.

Run ``uv run python scripts/benchmark/build_profile_datasets.py`` and commit
the manifest; ``--check`` fails if it is stale.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
from typing import Any

import numpy as np

from hebog.validation.datasets import (
    DatasetManifest,
    SyntheticRecipe,
    recipe_sha256,
)

_ROOT = Path(__file__).resolve().parents[2]
_OUTPUT = _ROOT / "config/datasets/complete-execution-profile.json"
_SEED_BASE = 2026091800
_NOISE_RMS = 1e-4
_BEAM_MAJOR_FWHM_PIXELS = 5.0
_BEAM_MINOR_FWHM_PIXELS = 4.0
_FWHM_PER_SIGMA = 2.0 * math.sqrt(2.0 * math.log(2.0))
_POINT_MAJOR_SIGMA = _BEAM_MAJOR_FWHM_PIXELS / _FWHM_PER_SIGMA
_POINT_MINOR_SIGMA = _BEAM_MINOR_FWHM_PIXELS / _FWHM_PER_SIGMA
_PIXEL_SCALE_DEGREES = 1.5 / 3600.0
_EDGE_MARGIN_PIXELS = 20
_SIZES = (512, 1024, 2048, 4096)
# Sources per 1,024² image. The dense grid spacing of about 12 beams keeps
# every source isolated.
_DENSITIES = (("empty", 0), ("dense", 256))


def _grid_sources(size: int, count: int, seed: int) -> list[dict[str, float]]:
    """Scatter beam-shaped sources with SNR 5 to 50 on a jittered grid."""
    if count == 0:
        return []
    generator = np.random.default_rng(seed)
    side = math.isqrt(count)
    spacing = (size - 2 * _EDGE_MARGIN_PIXELS) / side
    sources: list[dict[str, float]] = []
    for index in range(count):
        row, column = divmod(index, side)
        x, y = (
            _EDGE_MARGIN_PIXELS
            + spacing * (cell + 0.5 + generator.uniform(-0.3, 0.3))
            for cell in (column, row)
        )
        snr = math.exp(generator.uniform(math.log(5.0), math.log(50.0)))
        sources.append(
            {
                "x_pixel": round(x, 3),
                "y_pixel": round(y, 3),
                "peak_flux_jy_per_beam": round(snr, 3) * _NOISE_RMS,
                "major_sigma_pixels": _POINT_MAJOR_SIGMA,
                "minor_sigma_pixels": _POINT_MINOR_SIGMA,
                "rotation_degrees_counterclockwise_from_x": 0.0,
            }
        )
    return sources


def build_manifest() -> dict[str, Any]:
    """Return the validated manifest document."""
    datasets: list[dict[str, Any]] = []
    for index, (size, (density, count_per_1024)) in enumerate(
        ((size, density) for size in _SIZES for density in _DENSITIES),
        start=1,
    ):
        count = count_per_1024 * size * size // (1024 * 1024)
        seed = _SEED_BASE + index
        recipe = SyntheticRecipe.model_validate(
            {
                "generator": "hebog.synthetic.gaussian-noise",
                "generator_version": 3,
                "seed": seed,
                "shape_yx": [size, size],
                "background": 0.0,
                "noise_rms": _NOISE_RMS,
                "sources": _grid_sources(size, count, seed),
                "noise_rms_fractional_gradient_xy": [0.0, 0.0],
                "invalid_rectangles": [],
                "noise_correlation": {
                    "major_fwhm_pixels": _BEAM_MAJOR_FWHM_PIXELS,
                    "minor_fwhm_pixels": _BEAM_MINOR_FWHM_PIXELS,
                    "position_angle_degrees": 0.0,
                    "truncation_sigma": 4.0,
                },
            }
        )
        datasets.append(
            {
                "identifier": f"profile-{density}-{size}",
                "role": "development",
                "purpose": (
                    f"{count} isolated compact sources with SNR 5 to 50 on a "
                    f"{size} by {size} beam-correlated noise image, for "
                    "execution profiling."
                ),
                "provenance": (
                    "Generated by scripts/benchmark/build_profile_datasets.py "
                    "for the complete-execution profile; seed-disjoint from "
                    "earlier manifests."
                ),
                "redistribution": "generated-locally",
                "beam": {
                    "major_fwhm_pixels": _BEAM_MAJOR_FWHM_PIXELS,
                    "minor_fwhm_pixels": _BEAM_MINOR_FWHM_PIXELS,
                    "position_angle_degrees": 0.0,
                },
                "wcs": {
                    "frame": "icrs",
                    "reference_pixel_xy": [(size - 1) / 2.0, (size - 1) / 2.0],
                    "reference_sky_degrees": [180.0, 45.0],
                    "pixel_scale_degrees_xy": [
                        -_PIXEL_SCALE_DEGREES,
                        _PIXEL_SCALE_DEGREES,
                    ],
                    "rotation_degrees_counterclockwise": 0.0,
                },
                "expected_statistics": {
                    "background_jy_per_beam": 0.0,
                    "noise_rms_jy_per_beam": _NOISE_RMS,
                    "finite_fraction": 1.0,
                },
                "recipe": recipe.model_dump(mode="json"),
                "recipe_sha256": recipe_sha256(recipe),
            }
        )
    document: dict[str, Any] = {
        "schema_version": 1,
        "manifest_id": "complete-execution-profile",
        "datasets": datasets,
    }
    DatasetManifest.model_validate(document)
    return document


def main() -> None:
    """Write the manifest, or check that the committed one is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if stale")
    args = parser.parse_args()
    text = json.dumps(build_manifest(), indent=2, sort_keys=True) + "\n"
    if args.check:
        if _OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{_OUTPUT} is stale; rerun without --check")
        return
    _OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
